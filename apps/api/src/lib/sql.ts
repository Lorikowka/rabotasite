/**
 * Безопасная работа с пользовательским вводом в SQL-выражениях.
 *
 * Все запросы к БД строятся через Drizzle ORM, который параметризует значения
 * (SQL-инъекция через значения невозможна). Но в LIKE-шаблонах спецсимволы
 * `%` и `_` трактуются как wildcards, поэтому пользовательский ввод нужно
 * дополнительно экранировать.
 */

/** Экранирует спецсимволы LIKE обратным слэшем. */
export function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`);
}

/**
 * Готовый LIKE-шаблон вида `%значение%` с экранированными wildcards.
 * Использовать вместе с `escape '\\'` в SQL-выражении.
 */
export function likePattern(value: string): string {
  return `%${escapeLike(value)}%`;
}
